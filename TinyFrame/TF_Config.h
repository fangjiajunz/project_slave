#ifndef TF_CONFIG_H
#define TF_CONFIG_H

#include <stdint.h>
#include <stdio.h>  // 用于下面定义的 TF_Error() 宏
// #include <esp8266.h> // 当与 esphttpd 一起使用时

//----------------------------- 帧格式 ---------------------------------
// 可以根据你的特定应用需求调整格式

// 如果连接是可靠的，可以禁用 SOF 字节和校验和。
// 这可以节省最多 9 字节的开销。

// ,-----+-----+-----+------+------------+- - - -+-------------,
// | SOF | ID  | LEN | TYPE | HEAD_CKSUM | DATA  | DATA_CKSUM  |
// | 0-1 | 1-4 | 1-4 | 1-4  | 0-4        | ...   | 0-4         | <- 字节大小
// '-----+-----+-----+------+------------+- - - -+-------------'
// ,------+-----+------+------+------------+- - - -+-------------,
// | 帧头 | ID  | 长度 | 类型 |  头校验和  | 数据  | 数据校验和  |
// | 0-1  | 1-4 | 1-4  | 1-4  |    0-4     | ...   |    0-4      | <- 字节数
// '------+-----+------+------+------------+- - - -+-------------'

//	| 字段        | 字节数 | 说明                                                                                                                |
//  |-------------|--------|---------------------------------------------------------------------------------------------------------------------|
//  | 帧头 (SOF)  | 0-1    | Start Of Frame，帧起始标志，用于同步和识别帧的开始。值由 TF_SOF_BYTE 配置，默认 0x01。可通过 TF_USE_SOF_BYTE=0 禁用 |
//  | ID          | 1-4    | 帧标识符，用于匹配请求和响应。发送方分配 ID，接收方响应时使用相同 ID，这样就知道哪个响应对应哪个请求                |
//  | 长度 (LEN)  | 1-4    | 数据负载的字节数，不包括帧头和校验和                                                                                |
//  | 类型 (TYPE) | 1-4    | 消息类型，用于区分不同种类的消息（如：0x01=心跳，0x02=数据请求等），由用户自定义                                    |
//  | 头校验和    | 0-4    | 对 SOF+ID+LEN+TYPE 这些字段的校验和，用于验证帧头完整性                                                             |
//  | 数据 (DATA) | 可变   | 实际的消息负载，长度由 LEN 字段指定                                                                                 |
//  | 数据校验和  | 0-4    | 对 DATA 部分的校验和，用于验证数据完整性                                                                            |

// !!! 通信双方必须使用相同的配置 !!!

// 根据需要调整大小 (1,2,4)
#define TF_ID_BYTES 1
#define TF_LEN_BYTES 2
#define TF_TYPE_BYTES 1

// 校验和类型。可选项：
//   TF_CKSUM_NONE, TF_CKSUM_XOR, TF_CKSUM_CRC8, TF_CKSUM_CRC16, TF_CKSUM_CRC32
//   TF_CKSUM_CUSTOM8, TF_CKSUM_CUSTOM16, TF_CKSUM_CUSTOM32
// 自定义校验和需要你实现校验和函数（参见 TinyFrame.h）
#define TF_CKSUM_TYPE TF_CKSUM_CRC16

// 使用 SOF 字节标记帧的开始
#define TF_USE_SOF_BYTE 1
// SOF 字节的值（当 TF_USE_SOF_BYTE == 1 时）
#define TF_SOF_BYTE 0x01

//----------------------- 平台兼容性 ----------------------------

// 用于超时计数器 - 应足够大以容纳所有使用的超时值
typedef uint16_t TF_TICKS;

// 用于遍历监听器的循环
typedef uint8_t TF_COUNT;

//----------------------------- 参数 ----------------------------------

// 最大接收负载大小（静态缓冲区）
// 较大的负载将被拒绝。
#define TF_MAX_PAYLOAD_RX 1024
// 发送缓冲区大小。较大的负载将被分割成多个部分，
// 通过多次调用写函数发送。可以减小此值以降低 RAM 使用。
#define TF_SENDBUF_LEN 128

// --- 监听器数量 - 决定静态槽表的大小 ---

// 帧 ID 监听器（等待响应 / 多部分消息）
#define TF_MAX_ID_LST 10
// 帧类型监听器（等待具有特定第一个负载字节的帧）
#define TF_MAX_TYPE_LST 10
// 通用监听器（如果没有其他监听器捕获则作为后备）
#define TF_MAX_GEN_LST 5

// 接收和解析帧的超时时间
// ticks = 调用 TF_Tick() 的次数
#define TF_PARSER_TIMEOUT_TICKS 10

// 是否使用互斥锁 - 需要你实现 TF_ClaimTx() 和 TF_ReleaseTx()
#define TF_USE_MUTEX 0

// 错误报告函数。要禁用调试，改为空定义
#define TF_Error(format, ...) usb_printf("[TF] " format "\n", ##__VA_ARGS__)

//------------------------- 用户配置结束 ------------------------------

#endif  // TF_CONFIG_H
