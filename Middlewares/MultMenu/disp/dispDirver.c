/**
 * 在OLED显示器上绘制中文汉字
 *
 * @param x 汉字的左上角x坐标
 * @param y 汉字的左上角y坐标
 * @param index 汉字索引（0-41），对应 font_chinese.h 中的 Chinese_Char_Index 枚举
 *
 * 该函数使用字模数据和 u8g2_DrawXBMP 来绘制 16×16 的中文汉字
 */
void OLED_DrawChinese(uint16_t x, uint16_t y, uint8_t index)
{
    if (index >= 42) return;  // 安全检查：只有 42 个汉字

    // 反转位编码：阳码 ↔ 阴码
    uint8_t inverted_bitmap[32];
    for (int i = 0; i < 32; i++) {
        inverted_bitmap[i] = chinese_font[index][i] ^ 0xFF;
    }
    u8g2_DrawXBMP(&u8g2, x, y, 16, 16, inverted_bitmap);
}
